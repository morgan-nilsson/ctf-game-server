"""Emit the derived topology so the shell scripts and the referee agree.

`topology/*.sh` never hardcodes a player. It asks here, so adding the Nth
player is a config edit plus `ctfctl topology apply`.

  python3 -m orchestrator.topology env            # global shell vars
  python3 -m orchestrator.topology players        # one row per player
  python3 -m orchestrator.topology player <name>  # shell vars for one player
"""
from __future__ import annotations

import shlex
import sys

from .config import load as load_config

FIELDS = ("index", "name", "tap", "netns", "subnet", "host", "kernel_addr",
          "link_gw", "link_addr", "foot_gw", "foot_addr", "veth_host", "veth_ns",
          "bridge", "foot_net", "link_net")


def _emit(pairs) -> None:
    for key, value in pairs:
        print(f"{key}={shlex.quote(str(value))}")


def main(argv: list[str]) -> int:
    cfg = load_config(None)
    mode = argv[1] if len(argv) > 1 else "env"

    if mode == "env":
        _emit([
            ("CTF_ROOT", cfg.raw["paths"]["root"]),
            ("CTF_RUN", cfg.raw["paths"]["run"]),
            ("CTF_LOGS", cfg.raw["paths"].get("logs", "/var/log/ctf")),
            ("CTF_ARTIFACTS", cfg.raw["paths"]["artifacts"]),
            ("CTF_PLAYERS", " ".join(cfg.names)),
            ("CTF_VIEWER_BIND", cfg.p("net", "viewer_bind", default="10.9.0.1")),
            ("CTF_VIEWER_CIDR", cfg.p("net", "viewer_cidr", default="10.9.0.0/24")),
            ("CTF_CONTROL_BIND", cfg.p("net", "control_bind", default="10.9.1.1")),
            ("CTF_CONTROL_CIDR", cfg.p("net", "control_cidr", default="10.9.1.0/24")),
            ("CTF_GW_CONTROL_ADDR", cfg.p("net", "gw_control_addr", default="10.9.1.254")),
            ("CTF_SUBMIT_PORT", cfg.p("net", "submit_port", default=8001)),
            ("CTF_BOARD_PORT", cfg.p("net", "leaderboard_port", default=8000)),
            ("CTF_MTU", cfg.p("net", "alloc", "mtu", default=1500)),
            ("CTF_PLANE_MODE", cfg.p("net", "plane_mode", default="netns")),
            ("CTF_BRIDGES", " ".join(p.bridge for p in cfg.players)),
            ("CTF_HYPERVISOR", cfg.p("vm", "hypervisor", default="firecracker")),
            ("CTF_KERNEL", cfg.p("vm", "kernel", default="")),
            ("CTF_ROOTFS", cfg.p("vm", "rootfs", default="")),
            ("CTF_VCPUS", cfg.p("vm", "vcpus", default=1)),
            ("CTF_MEM_MIB", cfg.p("vm", "mem_mib", default=512)),
            ("CTF_SUBNETS", " ".join(p.subnet for p in cfg.players)),
        ])
        return 0

    if mode == "players":
        # index name tap netns subnet host kernel_addr link_gw link_addr foot_gw foot_addr
        for p in cfg.players:
            print(" ".join(str(getattr(p, f)) for f in FIELDS))
        return 0

    if mode == "nft":
        # Definitions consumed by topology/ctf.nft. Generated, because the
        # interface names and subnets are derived from the roster.
        quote = lambda xs: "{ " + ", ".join(f'"{x}"' for x in xs) + " }"
        plain = lambda xs: "{ " + ", ".join(str(x) for x in xs) + " }"
        print("# generated by orchestrator.topology — do not edit")
        mode = cfg.p("net", "plane_mode", default="netns")
        print(f'define ctrl_iface  = "gwc1"')
        print(f"define svc_brs     = " + quote(p.bridge for p in cfg.players))
        print(f'# plane_mode = {mode}')
        svc_if = (p.bridge if mode == "host" else p.tap for p in cfg.players)
        print(f"define svc_ifaces  = {quote(svc_if)}")
        print(f"define foot_ifaces = {quote(p.veth_host for p in cfg.players)}")
        print(f"define svc_nets    = {plain(p.subnet for p in cfg.players)}")
        print(f"define foot_nets   = {plain(p.foot_net for p in cfg.players)}")
        print(f"define link_nets   = {plain(p.link_net for p in cfg.players)}")
        print(f"define viewer_net  = {cfg.p('net', 'viewer_cidr', default='10.9.0.0/24')}")
        # Source addresses a foothold may legitimately claim: its own /30,
        # plus the referee's addresses — impersonating the checker's session
        # is the whole point of a blind ISN hijack (RULES §7). Anything else
        # is spoofing for its own sake and gets dropped.
        spoof_ok = ([p.foot_net for p in cfg.players]
                    + [p.link_net for p in cfg.players]
                    + [cfg.p("net", "control_cidr", default="10.9.1.0/24")])
        print(f"define spoof_ok    = {plain(spoof_ok)}")
        print(f"define control_net = {cfg.p('net', 'control_cidr', default='10.9.1.0/24')}")
        print(f"define board_port  = {cfg.p('net', 'leaderboard_port', default=8000)}")
        print(f"define submit_port = {cfg.p('net', 'submit_port', default=8001)}")
        return 0

    if mode == "player":
        if len(argv) < 3:
            print("usage: topology player <name>", file=sys.stderr)
            return 2
        p = cfg.player(argv[2])
        if p is None:
            print(f"no such player: {argv[2]}", file=sys.stderr)
            return 2
        _emit([(f"P_{f.upper()}", getattr(p, f)) for f in FIELDS])
        return 0

    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
